//! S3 `POST Object` request handling.

use super::{
    PostObjectInput, PostObjectOutput, PutObjectInput, PutObjectOutput, S3Request, S3Response,
    S3Result, Sqlite,
};

/// Stores an object from a browser-form POST upload.
pub(super) async fn post_object(
    sqlite: &Sqlite,
    req: S3Request<PostObjectInput>,
) -> S3Result<S3Response<PostObjectOutput>> {
    let response = super::put::put_object(
        sqlite,
        req.map_input(post_object_input_into_put_object_input),
    )
    .await?;
    Ok(response.map_output(put_object_output_into_post_object_output))
}

